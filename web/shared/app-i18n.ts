const DICTS: Readonly<Record<AppLang, Dict>> = { en, nl, ar };
const PLURALS: Readonly<Record<AppLang, PluralDict>> = { en: pluralEn, nl: pluralNl, ar: pluralAr };

export type Vars = Readonly<Record<string, string | number>>;

/** "{name}" → vars.name (unknown placeholders stay as they are). */
export function fill(text: string, vars?: Vars): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, k: string) => {
    const v = vars[k];
    return v === undefined ? m : String(v);
  });
}

/** A message in a given language (the pure core of t()). */
export function message(l: AppLang, key: MsgKey, vars?: Vars): string {
  return fill(DICTS[l][key] ?? en[key], vars);
}

/** A counted message: the plural category of `n` in that language, `n` filled in. */
export function plural(l: AppLang, key: PluralKey, n: number, vars?: Vars): string {
  const forms = PLURALS[l][key];
  let cat: Intl.LDMLPluralRule = "other";
  try {
    cat = new Intl.PluralRules(l).select(n);
  } catch {
    cat = n === 1 ? "one" : "other";
  }
  return fill(forms[cat] ?? forms.other, { n, ...vars });
}

/** Every message key (for the tests). */
export function msgKeys(): MsgKey[] {
  return Object.keys(en) as MsgKey[];
}

/** Every counted-message key (for the tests). */
export function pluralKeys(): PluralKey[] {
  return Object.keys(pluralEn) as PluralKey[];
}

/** The raw forms of a counted message in a language (for the tests). */
export function pluralForms(l: AppLang, key: PluralKey): PluralForms {
  return PLURALS[l][key];
}

/** Every key of every language is filled (for the tests). */
export function missingKeys(): string[] {
  const out: string[] = [];
  for (const l of APP_LANGS) {
    for (const k of Object.keys(en) as MsgKey[]) {
      if (typeof DICTS[l][k] !== "string" || DICTS[l][k].trim() === "") out.push(`${l}:${k}`);
    }
  }
  return out;
}

// --- the current language (browser) -------------------------------------------------------------

interface StorageLike {
  getItem(k: string): string | null;
  setItem(k: string, v: string): void;
}

interface Env {
  localStorage?: StorageLike;
  navigator?: { languages?: readonly string[]; language?: string };
  document?: { documentElement?: { lang: string; dir: string } };
}

function env(): Env {
  return globalThis as unknown as Env;
}

function read(key: string): string | null {
  try {
    return env().localStorage?.getItem(key) ?? null;
  } catch {
    return null;
  }
}

function detect(): AppLang {
  const nav = env().navigator;
  const browser = nav?.languages?.length ? nav.languages : nav?.language ? [nav.language] : [];
  return chooseLang({ app: read(APP_LANG_KEY), site: read(SITE_LANG_KEY), browser });
}

let current: AppLang | null = null;
const listeners = new Set<(l: AppLang) => void>();

export function lang(): AppLang {
  if (current === null) current = detect();
  return current;
}

/** Sets <html lang> and <html dir> to the current language. */
export function applyDocumentLang(): void {
  const root = env().document?.documentElement;
  if (!root) return;
  const l = lang();
  root.lang = l;
  root.dir = dirOf(l);
}

/** Switch the app language: remembered, applied to <html>, and announced to the page. */
export function setLang(l: AppLang): void {
  current = l;
  try {
    env().localStorage?.setItem(APP_LANG_KEY, l);
  } catch {
    // not remembered; the page still switches
  }
  applyDocumentLang();
  for (const fn of listeners) fn(l);
}

export function onLangChange(fn: (l: AppLang) => void): void {
  listeners.add(fn);
}

export function t(key: MsgKey, vars?: Vars): string {
  return message(lang(), key, vars);
}

export function tn(key: PluralKey, n: number, vars?: Vars): string {
  return plural(lang(), key, n, vars);
}

/** True when `key` is a message key (data-i18n attributes are checked at runtime). */
export function isMsgKey(key: string): key is MsgKey {
  return Object.hasOwn(en, key);
}

/** "18:42" today, else "2 Oct, 18:42", in the app language. */
export function fmtWhen(ms: number, now: number = Date.now()): string {
  const d = new Date(ms);
  const loc = localeOf(lang());
  const time = d.toLocaleTimeString(loc, { hour: "2-digit", minute: "2-digit" });
  if (d.toDateString() === new Date(now).toDateString()) return time;
  const day = d.toLocaleDateString(loc, { day: "numeric", month: "short" });
  return `${day}, ${time}`;
}

/** "$1.25" in the app language. */
export function fmtUsd(usd: number, l: AppLang = lang()): string {
  // Arabic writes "US$" after the number, which reorders badly inside Arabic text: there the
  // amount is "$1.25", isolated left to right (U+2066 … U+2069).
  const arabic = l === "ar";
  let text: string;
  try {
    text = new Intl.NumberFormat(arabic ? "en-US" : localeOf(l), {
      style: "currency",
      currency: "USD",
      currencyDisplay: "narrowSymbol",
      maximumFractionDigits: usd < 10 ? 2 : 0,
    }).format(usd);
  } catch {
    text = `$${usd.toFixed(2)}`;
  }
  return arabic ? `\u2066${text}\u2069` : text;
}
