// App chrome in English, Dutch and Arabic: login, sign-up, keys, the dashboard and the builder. The
// caption pages keep their own labels (web/shared/i18n.ts).
// Language choice: the app's own choice (localStorage "tj-app-lang"), then the website's
// ("tj-lang"), then the browser's languages, then English. Arabic pages are right-to-left.
// No DOM types here (the unit tests import this file under Node): the few browser globals are
// read through globalThis with structural types.

export type AppLang = "en" | "nl" | "ar";

export const APP_LANGS: readonly AppLang[] = ["en", "nl", "ar"];
export const APP_LANG_KEY = "tj-app-lang";
export const SITE_LANG_KEY = "tj-lang";

/** Names for the language switch: each language in its own words. */
export const LANG_LABELS: Readonly<Record<AppLang, { long: string; short: string }>> = {
  en: { long: "English", short: "EN" },
  nl: { long: "Nederlands", short: "NL" },
  ar: { long: "العربية", short: "عربي" },
};

/** "nl-BE" → "nl"; anything else than en/nl/ar → null. */
export function normalizeLang(raw: string | null | undefined): AppLang | null {
  if (typeof raw !== "string") return null;
  const base = raw.trim().toLowerCase().split(/[-_]/)[0] ?? "";
  return (APP_LANGS as readonly string[]).includes(base) ? (base as AppLang) : null;
}

/** The order of choice in the header above; the first usable answer wins. */
export function chooseLang(input: {
  app?: string | null;
  site?: string | null;
  browser?: readonly string[];
}): AppLang {
  for (const v of [input.app, input.site, ...(input.browser ?? [])]) {
    const l = normalizeLang(v);
    if (l !== null) return l;
  }
  return "en";
}

export function dirOf(l: AppLang): "rtl" | "ltr" {
  return l === "ar" ? "rtl" : "ltr";
}

/** Locale for dates and numbers (Arabic keeps Latin digits, like the technical details). */
export function localeOf(l: AppLang): string {
  return l === "ar" ? "ar-u-nu-latn" : l === "nl" ? "nl-NL" : "en-GB";
}

